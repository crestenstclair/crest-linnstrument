use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::{
    io::{BufRead, BufReader, Write},
    path::Path,
    process::{Child, ChildStdin, Command, Stdio},
    sync::mpsc::{self, Receiver},
    time::Duration,
};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FirmwareSnapshot {
    pub version: u32,
    pub firmware: String,
    pub build_hash: String,
    pub patch_hash: String,
    pub at_us: u64,
    pub model: u16,
    pub midi: Vec<(u64, u8)>,
    pub leds: Vec<[u8; 3]>,
    pub sensor_reads: u64,
    pub sensor_selects: u64,
    pub led_writes: u64,
}
#[derive(Deserialize)]
struct FixtureManifest {
    version: u32,
    firmware: String,
    build_hash: String,
    flash_sha256: String,
    model: u16,
}
pub struct Worker {
    child: Child,
    input: ChildStdin,
    responses: Receiver<Result<FirmwareSnapshot, String>>,
}
impl Worker {
    pub fn start(
        executable: &Path,
        flash: &Path,
        model: u16,
    ) -> Result<(Self, FirmwareSnapshot), String> {
        let manifest: FixtureManifest = serde_json::from_slice(
            &std::fs::read(flash.with_extension("json")).map_err(|e| e.to_string())?,
        )
        .map_err(|e| e.to_string())?;
        let bytes = std::fs::read(flash).map_err(|e| e.to_string())?;
        if manifest.version != 1
            || manifest.model != model
            || manifest.firmware != "54bb1c9d355b1075b474ade0a0246b80ff7f3524"
            || format!("{:x}", Sha256::digest(&bytes)) != manifest.flash_sha256
        {
            return Err("incompatible flash fixture".into());
        }
        let mut child = Command::new(executable)
            .arg(model.to_string())
            .arg(flash)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::inherit())
            .spawn()
            .map_err(|e| e.to_string())?;
        let input = child.stdin.take().ok_or("missing stdin")?;
        let output = child.stdout.take().ok_or("missing stdout")?;
        let (sender, responses) = mpsc::sync_channel(2);
        std::thread::spawn(move || {
            let mut reader = BufReader::new(output);
            loop {
                let mut line = String::new();
                let result = std::io::Read::take(&mut reader, 2_000_000).read_line(&mut line);
                let parsed = match result {
                    Ok(0) => Err("firmware disconnected".into()),
                    Ok(_) if line.len() >= 2_000_000 => Err("firmware response too large".into()),
                    Ok(_) => serde_json::from_str(&line).map_err(|e| e.to_string()),
                    Err(e) => Err(e.to_string()),
                };
                let failed = parsed.is_err();
                if sender.send(parsed).is_err() || failed {
                    break;
                }
            }
        });
        let mut worker = Self {
            child,
            input,
            responses,
        };
        let first = worker.receive()?;
        if first.build_hash != manifest.build_hash {
            return Err("fixture was generated by another simulator build".into());
        }
        Ok((worker, first))
    }
    fn receive(&mut self) -> Result<FirmwareSnapshot, String> {
        let snapshot = self
            .responses
            .recv_timeout(Duration::from_secs(5))
            .map_err(|_| "firmware response timeout".to_string())??;
        if snapshot.version != 1 || snapshot.firmware != "54bb1c9d355b1075b474ade0a0246b80ff7f3524"
        {
            return Err("incompatible firmware worker".into());
        }
        Ok(snapshot)
    }
    #[cfg(test)]
    pub(crate) fn kill_for_test(&mut self) {
        self.child.kill().unwrap();
        self.child.wait().unwrap();
    }
    pub fn request(&mut self, command: &str) -> Result<FirmwareSnapshot, String> {
        if command.contains('\n') || command.len() > 65536 {
            return Err("invalid worker command".into());
        }
        writeln!(self.input, "{command}")
            .and_then(|_| self.input.flush())
            .map_err(|e| e.to_string())?;
        self.receive()
    }
}
impl Drop for Worker {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}
