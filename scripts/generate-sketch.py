#!/usr/bin/env python3
"""Reproduce Arduino's sketch assembly using pinned, extracted prototypes.

--extract refreshes prototypes from the ARM build's actual CLI preprocessing.
The source remains unmodified; generated files are private build artifacts.
"""
import hashlib
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/linnstrument-firmware'
PIN = '54bb1c9d355b1075b474ade0a0246b80ff7f3524'
assert subprocess.check_output(['git', '-C', str(SOURCE), 'rev-parse', 'HEAD'], text=True).strip() == PIN
assert not subprocess.check_output(['git', '-C', str(SOURCE), 'diff', '--name-only'], text=True).strip(), 'upstream must remain unmodified'
PROTOTYPES = ROOT / 'firmware/native/prototypes.inc'
if '--extract' in sys.argv:
    generated = (ROOT / 'target/firmware-arm/sketch/linnstrument-firmware.ino.cpp').read_text()
    marker = f'#line 900 "{SOURCE}/linnstrument-firmware.ino"\n'
    declarations = generated.split(marker)[1]
    declarations = re.sub(r'^#line.*\n', '', declarations, flags=re.M)
    PROTOTYPES.write_text('// Generated by Arduino CLI 1.3.1 (ctags 5.8-arduino11). Apache-2.0, Roger Linn Design.\n' + declarations)

output = ROOT / 'target/firmware-native/generated'
output.mkdir(parents=True, exist_ok=True)

def desktop_types(text):
    # Rewrite C++ tokens only, not strings/comments. SAM has ILP32, desktop LP64.
    tokens = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\bunsigned\s+long\b|\blong\b|\bULONG_MAX\b', re.S)
    def replace(match):
        value = match.group()
        return {'unsigned long': 'uint32_t', 'long': 'int32_t', 'ULONG_MAX': 'UINT32_MAX'}.get(value, value)
    return tokens.sub(replace, text)

for path in SOURCE.glob('*.ino'):
    (output / path.name).write_text(path.read_text())
for patch in sorted((ROOT / 'firmware/patches').glob('*.patch')):
    subprocess.run(['patch', '-s', '-p1', '-i', str(patch)], cwd=output, check=True)
main = (output / 'linnstrument-firmware.ino').read_text()
marker = 'static int alignToByteBoundary(int value) {'
assert main.count(marker) == 1
main = main.replace(marker, PROTOTYPES.read_text() + '\n' + marker)
parts = ['#include <Arduino.h>\n', main]
for path in sorted(output.glob('*.ino')):
    if path.name != 'linnstrument-firmware.ino':
        parts.append(f'\n#line 1 "{path.name}"\n' + path.read_text())
for path in SOURCE.glob('*.h'):
    (output / path.name).write_text(desktop_types(path.read_text()))
sketch = desktop_types('\n'.join(parts))
(output / 'sketch.cpp').write_text(sketch)
(output / 'source.sha256').write_text(hashlib.sha256(sketch.encode()).hexdigest() + '\n')
print(output / 'sketch.cpp')

inputs = [ROOT/'scripts/generate-sketch.py', ROOT/'scripts/build-native.sh']
inputs += sorted((ROOT/'firmware/native').rglob('*'))
inputs += sorted((ROOT/'firmware/patches').glob('*.patch'))
build = hashlib.sha256(sketch.encode())
patches = hashlib.sha256()
for path in inputs:
    if path.is_file():
        build.update(str(path.relative_to(ROOT)).encode())
        build.update(path.read_bytes())
for path in sorted((ROOT/'firmware/patches').glob('*.patch')):
    patches.update(path.read_bytes())
(output/'identity.h').write_text(f'#pragma once\n#define SIM_BUILD_HASH "{build.hexdigest()}"\n#define SIM_PATCH_HASH "{patches.hexdigest()}"\n')
